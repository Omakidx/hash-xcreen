#!/usr/bin/env bash
# Network isolation test: a container must not reach 169.254.169.254 or the host's listening ports.
# Uses a dedicated bridge (s3-br0) with an Incus network ACL; needs no host sudo beyond incus access
# (on a VPS the installer runs as root anyway). A second container impersonates the metadata service.
#
# Usage: net-test.sh        Prints PASS/FAIL lines. Cleans up everything named s3-net*/s3-br0/s3-isolate.
set -uo pipefail
here=$(cd "$(dirname "$0")" && pwd)
BR=s3-br0 ACL=s3-isolate T=s3-net-target
SUBNET=10.77.3 PORT=18099

cleanup() {
  incus delete -f "$T" 2>/dev/null
  [ "$(id -u)" = 0 ] && ip addr del 169.254.169.254/32 dev lo 2>/dev/null
  [ -n "${msrv:-}" ] && kill "$msrv" 2>/dev/null
  incus network delete "$BR" 2>/dev/null
  incus network acl delete "$ACL" 2>/dev/null
  [ -n "${srv:-}" ] && kill "$srv" 2>/dev/null
}
trap cleanup EXIT
cleanup

gw=$SUBNET.1
host_ips=$(ip -4 -o addr show scope global | awk '{print $4}' | cut -d/ -f1 | grep -v "^$gw$" | tr '\n' ' ')
host_ip6=$(ip -6 -o addr show scope global | awk '{print $4}' | cut -d/ -f1 | grep -v '^fd42' | head -3 | tr '\n' ' ')
echo "bridge gateway=$gw host_ipv4s=[$host_ips] host_ipv6s=[$host_ip6]"

incus network create "$BR" ipv4.address=$gw/24 ipv4.nat=true ipv6.address=none >/dev/null
incus launch --quiet images:ubuntu/24.04 "$T" --network "$BR" >/dev/null
for c in $T; do incus exec $c -- sh -c 'for i in $(seq 60); do systemctl is-system-running --quiet 2>/dev/null || [ "$(systemctl is-system-running 2>/dev/null)" = degraded ] && exit 0; sleep 1; done; exit 1'; done

if [ "$(id -u)" = 0 ]; then
  ip addr add 169.254.169.254/32 dev lo
  (cd /tmp && python3 -m http.server 80 --bind 169.254.169.254 >/dev/null 2>&1) & msrv=$!
  have_meta=1
else
  echo "not root: cannot add 169.254.169.254 to the host loopback, metadata probes are skipped"
  have_meta=0
fi
# A host-side service reachable on all addresses, standing in for the agent port.
(cd /tmp && python3 -m http.server $PORT --bind 0.0.0.0 >/dev/null 2>&1) & srv=$!
sleep 2

probe() { # name url expect(reach|block)
  code=$(incus exec $T -- curl -s -m 5 -o /dev/null -w '%{http_code}' "$2" 2>/dev/null); code=${code:-000}
  if [ "$3" = reach ]; then [ "$code" = 200 ] && echo "PASS  $1 reachable ($code)" || echo "FAIL  $1 not reachable ($code)"
  else [ "$code" = 000 ] && echo "PASS  $1 blocked" || echo "FAIL  $1 reachable ($code)"; fi
}
checks() { # phase expectation
  echo "--- $1"
  [ "$have_meta" = 1 ] && probe "metadata 169.254.169.254:80" http://169.254.169.254/ "$2"
  probe "host via bridge gateway $gw:$PORT" http://$gw:$PORT/ "$2"
  for h in $host_ips; do probe "host public $h:$PORT" http://$h:$PORT/ "$2"; done
  for h in $host_ip6; do probe "host public [$h]:$PORT" "http://[$h]:$PORT/" "$2"; done
}

checks "baseline, no ACL (expect everything reachable)" reach

# The ACL: drop first, then allow the rest. `incus network acl` rules are evaluated drop > reject > allow.
incus network acl create $ACL >/dev/null
incus network acl rule add $ACL egress action=drop destination=169.254.169.254/32 description="cloud metadata"
incus network acl rule add $ACL egress action=drop destination=fd00:ec2::254/128 description="cloud metadata (AWS IPv6)"
incus network acl rule add $ACL egress action=drop destination=$gw/32 description="host via the bridge gateway"
for h in $host_ips; do incus network acl rule add $ACL egress action=drop destination=$h/32 description="host public address"; done
for h in $host_ip6; do incus network acl rule add $ACL egress action=drop destination=$h/128 description="host public address"; done
incus network acl rule add $ACL egress action=allow description="everything else"
incus network set $BR security.acls=$ACL security.acls.default.egress.action=allow
sleep 2
checks "with ACL $ACL on $BR (expect everything blocked)" block

echo "--- what must still work"
c=$(incus exec $T -- curl -s -m 10 -o /dev/null -w '%{http_code}' https://deb.debian.org/ 2>/dev/null)
[ "$c" = 200 ] && echo "PASS  internet over HTTPS ($c)" || echo "FAIL  internet over HTTPS ($c)"
incus exec $T -- getent hosts deb.debian.org >/dev/null && echo "PASS  DNS resolution" || echo "FAIL  DNS resolution (dnsmasq on the gateway is blocked by the gateway rule)"
incus exec $T -- sh -c 'ip -4 addr show eth0 | grep -q "inet $0"' "$SUBNET" && echo "PASS  DHCP lease kept"
echo "--- nft rules generated by Incus (needs root to list): nft list table bridge incus"
