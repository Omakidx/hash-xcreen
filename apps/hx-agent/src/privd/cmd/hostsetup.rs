//! `SetupHost` (ipc.md 6.4): pool, bridge, ACL, profiles, the host nftables ruleset, the sysctl
//! drop-in and the `DOCKER-USER` rules. Every step is idempotent, so a failed run is simply run
//! again.
//!
//! What a caller may choose is small: the pool size, and (Admin only) a pool device, private
//! network access, extra host addresses and the bridge subnet. The ruleset, the sysctl text and
//! every name are generated here or in `hx-provision`; nothing is taken from the request as text
//! to load.

use std::net::IpAddr;
use std::time::Duration;

use hx_ipc::privd::pb::{self, ErrorDetail, ProgressStage, Role, response};
use hx_provision::host::{
    Ensured, HostReport, HostSpec, MAX_POOL_GIB, MIN_POOL_GIB, PoolSource, default_loop_size_gib,
    ensure_host,
};
use hx_provision::incus::{IncusError, Transport};

use super::blockdev::{BlockEnv, verify_pool_device};
use crate::privd::daemon::{Ctx, Daemon, Reply};
use crate::privd::error::CmdError;
use crate::privd::probe::{SYSCTLS, parse_ip_addresses};
use crate::privd::runner::{Program, Tool};
use crate::privd::state::{Flag, HostSetupRecord, write_atomic};

/// The sysctl drop-in, a constant template (ipc.md 6.4 step 4).
pub fn sysctl_text() -> String {
    let mut s = String::from(
        "# hash-xcreen: limits shared by all unprivileged containers (generated by hx-privd)\n",
    );
    for (k, v) in SYSCTLS {
        s.push_str(&format!("{k} = {v}\n"));
    }
    s
}

/// The two `DOCKER-USER` rules for our bridge, as `iptables` argument lists after the chain
/// (ipc.md 6.4 step 5): traffic from the bridge, and the replies back to it.
pub fn docker_user_rules(bridge: &str) -> [Vec<String>; 2] {
    let s = |v: &[&str]| v.iter().map(|x| (*x).to_string()).collect::<Vec<_>>();
    [
        s(&["-i", bridge, "-j", "ACCEPT"]),
        s(&[
            "-o",
            bridge,
            "-m",
            "conntrack",
            "--ctstate",
            "RELATED,ESTABLISHED",
            "-j",
            "ACCEPT",
        ]),
    ]
}

/// What `SetupHost` applies.
#[derive(Debug, Clone)]
pub struct HostParams {
    /// Pool backing store.
    pub pool: PoolSource,
    /// `auto` or `a.b.c.d/nn`.
    pub ipv4: String,
    /// Admin's `allow_private_networks`.
    pub allow_private_networks: bool,
    /// Admin's `extra_host_addresses`.
    pub extra: Vec<IpAddr>,
}

fn pb_ensured(e: Ensured) -> pb::Ensured {
    match e {
        Ensured::Created => pb::Ensured::Created,
        Ensured::Existed => pb::Ensured::Existed,
        Ensured::Updated => pb::Ensured::Updated,
    }
}

/// Maps an `ensure_host` failure to the step it names (`POOL` or `NETWORK`).
fn host_error(e: IncusError) -> CmdError {
    let text = e.to_string().to_lowercase();
    let detail = if text.contains("pool") {
        ErrorDetail::Pool
    } else {
        ErrorDetail::Network
    };
    CmdError::from(e).with_detail(detail)
}

/// `SetupHost` (class S).
pub async fn setup_host<T: Transport + Clone + 'static>(
    d: &Daemon<T>,
    ctx: &mut Ctx,
    r: pb::SetupHostRequest,
) -> Result<Reply, CmdError> {
    // Defence in depth: `authorize` already refused these for Gateway; this is the check that
    // matters if a caller ever reaches this function another way.
    if ctx.role != Role::Admin
        && (r.pool_device.is_some()
            || r.allow_private_networks.is_some()
            || r.extra_host_addresses.is_some()
            || r.ipv4.is_some())
    {
        return Err(CmdError::denied("setup_host: Admin-only argument"));
    }
    let _host = d.lock_host(ctx).await?;
    ctx.progress.stage(ProgressStage::Host, "checking the host");

    let free = d.probe.incus_dir_free();
    let pool = if let Some(dev) = &r.pool_device {
        let path = verify_pool_device(dev, &BlockEnv::system(), &*d.runner).await?;
        PoolSource::Device(path)
    } else {
        let free = free.ok_or_else(|| {
            CmdError::precondition(
                ErrorDetail::Pool,
                "cannot read the free space of Incus's storage directory",
            )
        })?;
        let size = if r.pool_size_gib == 0 {
            default_loop_size_gib(free)
        } else {
            u64::from(r.pool_size_gib)
        };
        if !(MIN_POOL_GIB..=MAX_POOL_GIB).contains(&size) {
            return Err(CmdError::invalid("setup_host.pool_size_gib"));
        }
        // At most 60% of the free space (ipc.md 6.4).
        if size.saturating_mul(1 << 30) > free / 10 * 6 {
            return Err(CmdError::precondition(
                ErrorDetail::Pool,
                "setup_host.pool_size_gib: more than 60% of the free space",
            ));
        }
        PoolSource::LoopFile { size_gib: size }
    };
    // Only Admin may change `allow_private_networks` and `extra_host_addresses`. A Gateway call
    // (which cannot carry them) keeps what Admin last set, so it can neither drop the Admin's
    // /32 rules from the ACL nor reset the private-network option (ipc.md 1.2).
    let stored = d.read_state(|s| s.host.clone()).unwrap_or_default();
    let parse = |v: &[String]| -> Vec<IpAddr> { v.iter().filter_map(|a| a.parse().ok()).collect() };
    let (allow_private_networks, extra): (bool, Vec<IpAddr>) = if ctx.role == Role::Admin {
        (
            r.allow_private_networks
                .unwrap_or(stored.allow_private_networks),
            match &r.extra_host_addresses {
                Some(l) => parse(&l.addresses),
                None => parse(&stored.extra_host_addresses),
            },
        )
    } else {
        (
            stored.allow_private_networks,
            parse(&stored.extra_host_addresses),
        )
    };
    let params = HostParams {
        pool,
        ipv4: r.ipv4.clone().unwrap_or_else(|| "auto".into()),
        allow_private_networks,
        extra,
    };
    let result = d.apply_host(ctx, &params).await?;
    d.mutate_state(|s| {
        s.host = Some(HostSetupRecord {
            allow_private_networks: params.allow_private_networks,
            extra_host_addresses: params.extra.iter().map(ToString::to_string).collect(),
        });
    })?;
    ctx.progress
        .emit(ProgressStage::Host, 0, 0, "host ready", 100, true);
    Ok(response::Result::SetupHost(result))
}

impl<T: Transport + Clone + 'static> Daemon<T> {
    /// Every address of every interface except our own bridge, plus `extra` (ipc.md 6.4 step 1).
    pub async fn host_addresses(&self, extra: &[IpAddr]) -> Result<Vec<IpAddr>, CmdError> {
        let out = self
            .runner
            .run(
                Program::new(Tool::Ip, &["-j", "address", "show"])
                    .with_timeout(Duration::from_secs(10)),
            )
            .await
            .map_err(CmdError::from)?;
        if !out.success() {
            return Err(CmdError::internal("cannot list the host's addresses")
                .with_detail(ErrorDetail::Network));
        }
        let mut v = parse_ip_addresses(&out.stdout, &self.cfg.naming.bridge).map_err(|why| {
            CmdError::internal(format!("cannot list the host's addresses: {why}"))
                .with_detail(ErrorDetail::Network)
        })?;
        for e in extra {
            if !v.contains(e) {
                v.push(*e);
            }
        }
        Ok(v)
    }

    /// Steps 1 to 5 of `SetupHost`; also what the automatic re-run uses. The caller holds the
    /// host lock.
    pub async fn apply_host(
        &self,
        ctx: &Ctx,
        p: &HostParams,
    ) -> Result<pb::SetupHostResult, CmdError> {
        let host_addresses = self.host_addresses(&p.extra).await?;
        let spec = HostSpec {
            naming: self.cfg.naming.clone(),
            pool: p.pool.clone(),
            ipv4: p.ipv4.clone(),
            host_addresses,
            allow_private_networks: p.allow_private_networks,
        };
        spec.validate()
            .map_err(|e| CmdError::invalid(e.to_string()))?;
        let client = self.incus.scoped();
        let report: HostReport = self
            .run_cancellable(ctx, &client, None, async {
                ensure_host(&client, &spec).await.map_err(host_error)
            })
            .await?;

        self.load_firewall(&report.host_firewall).await?;
        self.apply_sysctl().await?;
        let docker_user = self.apply_docker_user_rules().await;
        Ok(pb::SetupHostResult {
            pool: pb_ensured(report.pool) as i32,
            network: pb_ensured(report.network) as i32,
            acl: pb_ensured(report.acl) as i32,
            desktop_profile: pb_ensured(report.desktop_profile) as i32,
            compat_profile: pb_ensured(report.compat_profile) as i32,
            gateway_ip: report.gateway.map(|g| g.to_string()).unwrap_or_default(),
            firewall_loaded: true,
            sysctl_applied: true,
            docker_user_rules: docker_user as i32,
        })
    }

    /// Writes the generated ruleset to `cfg.firewall_file` (root-owned, 0600), checks it with
    /// `nft -c -f`, loads it with `nft -f` and confirms the table exists. The ruleset text comes
    /// from `hx-provision`, never from a caller; it reaches `nft` as a file path privd chose.
    pub async fn load_firewall(&self, ruleset: &str) -> Result<(), CmdError> {
        let nft_err = |m: &str| CmdError::internal(m.to_string()).with_detail(ErrorDetail::Nft);
        if let Some(dir) = self.cfg.firewall_file.parent() {
            std::fs::create_dir_all(dir).map_err(CmdError::from)?;
        }
        write_atomic(&self.cfg.firewall_file, ruleset.as_bytes(), 0o600).map_err(CmdError::from)?;
        let file = self.cfg.firewall_file.to_string_lossy().into_owned();
        let run = |args: &[&str]| {
            let p = Program::new(Tool::Nft, args).with_timeout(Duration::from_secs(30));
            async move { self.runner.run(p).await }
        };
        let check = run(&["-c", "-f", &file]).await.map_err(CmdError::from)?;
        if !check.success() {
            return Err(nft_err("the generated ruleset does not pass `nft -c`"));
        }
        let load = run(&["-f", &file]).await.map_err(CmdError::from)?;
        if !load.success() {
            return Err(nft_err("`nft -f` failed to load the ruleset"));
        }
        let table = run(&["list", "table", "inet", "hx"])
            .await
            .map_err(CmdError::from)?;
        if !table.success() {
            return Err(nft_err("table `inet hx` is not present after loading"));
        }
        Ok(())
    }

    /// Writes the sysctl drop-in, applies it with `sysctl --system` and reads the values back.
    pub async fn apply_sysctl(&self) -> Result<(), CmdError> {
        let err = |m: &str| CmdError::internal(m.to_string()).with_detail(ErrorDetail::Sysctl);
        write_atomic(&self.cfg.sysctl_file, sysctl_text().as_bytes(), 0o644)
            .map_err(CmdError::from)?;
        let out = self
            .runner
            .run(Program::new(Tool::Sysctl, &["--system"]).with_timeout(Duration::from_secs(30)))
            .await
            .map_err(CmdError::from)?;
        if !out.success() {
            return Err(err("`sysctl --system` failed"));
        }
        if !self.probe.sysctl_ok() {
            return Err(err("the sysctl values did not take effect"));
        }
        Ok(())
    }

    /// Step 5: if a host Docker is present (`DOCKER-USER` exists), ensure the two accept rules for
    /// our bridge (`-C`, then `-I` if missing). A failure sets `HOST_DOCKER_FORWARDING` and is
    /// reported, but does not fail the command.
    pub async fn apply_docker_user_rules(&self) -> pb::DockerUserRules {
        let run = |args: Vec<String>| async move {
            let p = Program {
                tool: Tool::Iptables,
                args,
                stdin: None,
                timeout: Duration::from_secs(10),
            };
            self.runner.run(p).await
        };
        let chain = |extra: &[&str]| extra.iter().map(|s| (*s).to_string()).collect::<Vec<_>>();
        let present = run(chain(&["-n", "-L", "DOCKER-USER"]))
            .await
            .is_ok_and(|o| o.success());
        if !present {
            self.set_flag(None, Flag::HostDockerForwarding, false);
            return pb::DockerUserRules::NotPresent;
        }
        let mut ok = true;
        for rule in docker_user_rules(&self.cfg.naming.bridge) {
            let mut check = vec!["-C".to_string(), "DOCKER-USER".to_string()];
            check.extend(rule.iter().cloned());
            if run(check).await.is_ok_and(|o| o.success()) {
                continue;
            }
            let mut insert = vec!["-I".to_string(), "DOCKER-USER".to_string(), "1".to_string()];
            insert.extend(rule.iter().cloned());
            ok &= run(insert).await.is_ok_and(|o| o.success());
        }
        self.set_flag(None, Flag::HostDockerForwarding, !ok);
        if ok {
            pb::DockerUserRules::Applied
        } else {
            pb::DockerUserRules::Failed
        }
    }

    /// The automatic re-run of steps 1 to 3 after a host address appeared or disappeared (ipc.md
    /// 6.4, last paragraph; the README requires `ensure_host` to be re-run when `host_addresses`
    /// change). It uses what the last `SetupHost` recorded, and does nothing before one.
    pub async fn refresh_host(&self) -> Result<bool, CmdError> {
        let Some(rec) = self.read_state(|s| s.host.clone()) else {
            return Ok(false);
        };
        let ctx = Ctx::new(Role::Admin);
        let _g = self.lock_host(&ctx).await?;
        let pool = self
            .incus
            .get_storage_pool(&self.cfg.naming.pool)
            .await?
            .map(|_| PoolSource::LoopFile {
                size_gib: MIN_POOL_GIB,
            });
        let Some(pool) = pool else { return Ok(false) };
        let params = HostParams {
            // An existing pool is left alone by `ensure_host`, so the placeholder size is unused.
            pool,
            ipv4: "auto".into(),
            allow_private_networks: rec.allow_private_networks,
            extra: rec
                .extra_host_addresses
                .iter()
                .filter_map(|a| a.parse().ok())
                .collect(),
        };
        let spec_addresses = self.host_addresses(&params.extra).await?;
        let spec = HostSpec {
            naming: self.cfg.naming.clone(),
            pool: params.pool.clone(),
            ipv4: params.ipv4.clone(),
            host_addresses: spec_addresses,
            allow_private_networks: params.allow_private_networks,
        };
        let client = self.incus.scoped();
        let report = ensure_host(&client, &spec).await.map_err(host_error)?;
        self.load_firewall(&report.host_firewall).await?;
        self.audit_notice("host ruleset refreshed after an address change");
        Ok(true)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_sysctl_text_is_the_constant_template() {
        let t = sysctl_text();
        for (k, v) in SYSCTLS {
            assert!(t.contains(&format!("{k} = {v}\n")), "{k}");
        }
        assert_eq!(t.lines().count(), 1 + SYSCTLS.len());
    }

    #[test]
    fn docker_user_rules_name_only_our_bridge() {
        let [a, b] = docker_user_rules("hxbr0");
        assert_eq!(a, ["-i", "hxbr0", "-j", "ACCEPT"]);
        assert!(b.contains(&"hxbr0".to_string()) && b.contains(&"RELATED,ESTABLISHED".to_string()));
    }

    #[test]
    fn host_errors_name_the_step() {
        let e = host_error(IncusError::Api {
            code: 400,
            message: "Storage pool create failed".into(),
        });
        assert_eq!(e.detail, ErrorDetail::Pool);
        let e = host_error(IncusError::Api {
            code: 400,
            message: "bridge address invalid".into(),
        });
        assert_eq!(e.detail, ErrorDetail::Network);
    }
}
